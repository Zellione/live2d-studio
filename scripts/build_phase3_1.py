"""Replay the reviewed Girl2-only facial recipe through authenticated loopback MCP."""
import argparse
import json
from pathlib import Path
from live2d_studio.animation import package
from live2d_studio.expressive import recipe, blush_png
from live2d_studio.manifest import digest, write_json
from live2d_studio.mcp import MCP, Operations

SOURCE_HASH='bf185db0784cc658480c321f4f6e21f94d4176c4c3dca086993a64862e73c8ea'
FACE='artwork:bff53406988f'


def result(data):
    return data.get('result',data)


def build(source,output,endpoint):
    source,output=source.resolve(),output.resolve()
    if output.exists():raise FileExistsError('Use a fresh output directory')
    if digest(source)!=SOURCE_HASH:raise ValueError('Expected accepted Phase 3 Girl2 project')
    reviewed=json.loads((Path(__file__).resolve().parents[1]/'recipes/girl2-expressive.json').read_text())
    if recipe()!=reviewed:raise ValueError('Recipe differs from reviewed contract')
    client=MCP(endpoint);output.mkdir(parents=True);op=Operations(client,output)
    context=client.tool('workspace_inspect',{'request':{'scope':'project'}})
    if context['data'].get('loaded'):op.call('project_save_as',dict(path=str(output/'editor-snapshot.psd2live')))
    op.call('project_open',dict(path=str(source)))
    # Geometry first. Expressions are published once all their parameters exist.
    for step in reviewed:
        if step['operation']!='expression_put':op.call(step['operation'],step['request'])
    blush_png(output/'blush.png')
    ref=result(op.call('asset_prepare_reference',dict(layer_id=FACE,piece_id='phase31-blush',background_color='#FFFFFF',target_anchors={'left':dict(x=380,y=345),'right':dict(x=540,y=345)})))
    asset=result(op.call('asset_import_png',dict(reference_id=ref['id'],png_path=str(output/'blush.png'),require_transparency=True)))
    registration=result(op.call('asset_register',dict(asset_id=asset['assetId'],mode='absolute',transform=dict(x=0,y=0,scale_x=1,scale_y=1))))
    op.call('layer_add_from_asset',dict(asset_id=asset['assetId'],registration_id=registration['id'],layer_id='agent:phase31-blush',name='Procedural cheek blush',semantic_tag='unknown',parent_deformer_id='DeformFaceNinePose',insertion=dict(mode='above',reference_layer_id=FACE),opacity=1))
    found=client.tool('workspace_inspect',{'request':{'scope':'objects','query':'Procedural cheek blush'}})['data']['items']
    if len(found)!=1 or found[0]['target']!='mesh:ArtMeshImage':raise ValueError('Unexpected blush mesh; inspect before editing')
    op.call('parameter_create',dict(parameter_id='ParamBlush',name='Cheek blush',min=0,max=1,default=0))
    op.call('keyform_apply',dict(changes=[dict(op='set',target='mesh:ArtMeshImage',key={'ParamBlush':v},channels={'opacity':v}) for v in [0,1]]))
    op.call('rig_edit_structure',dict(edits=[dict(action='static',kind='mesh',id='ArtMeshImage',draw_order=85)]))
    for step in reviewed:
        if step['operation']=='expression_put':op.call(step['operation'],step['request'])
    op.call('project_save_as',dict(path=str(output/'character.psd2live')))
    op.call('project_export_psd',dict(path=str(output/'character.psd'),scale=1))
    op.call('project_open',dict(path=str(output/'character.psd2live')))
    op.call('project_export_model',dict(output_directory=str(output/'export')))
    write_json(output/'validation.json',package(output/'export',output/'runtime'))
    write_json(output/'provenance.json',dict(source_sha256=SOURCE_HASH,recipe_sha256=digest(Path(__file__).resolve().parents[1]/'recipes/girl2-expressive.json'),
        blush_sha256=digest(output/'blush.png'),blush='Original deterministic Gaussian cheek tint, native alpha, max 70/255; generated by expressive.blush_png. CC0-1.0. No image model.',
        source_rights='Girl2 OpenGameArt CC0; inherited Phase 3 source provenance',visual_gate='requires_review',production=False))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source',type=Path,default=Path('runs/phase3-final/character.psd2live'))
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--endpoint',default='http://127.0.0.1:23871/mcp')
    a=p.parse_args();build(a.source,a.output,a.endpoint)
